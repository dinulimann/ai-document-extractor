"""Runs the extractor on samples/*.pdf and compares against samples/expected.json.

    python scripts/evaluate.py            # writes docs/evaluation.md

Field accuracy counts exact matches after light normalisation (case and
whitespace for text, 0.01 tolerance for numbers). A line item counts as correct
only if all four of its fields match.
"""

import json
import platform
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from app import config  # noqa: E402
from app.extract import extract_pdf  # noqa: E402
from app.validate import validate  # noqa: E402

FIELDS = ["vendor_name", "vendor_tax_id", "invoice_number", "invoice_date", "due_date",
          "currency", "bill_to", "subtotal", "tax", "total"]


def same(a, b) -> bool:
    if isinstance(a, (int, float)) or isinstance(b, (int, float)):
        try:
            return abs(float(a) - float(b)) < 0.01
        except (TypeError, ValueError):
            return False
    norm = lambda v: " ".join(str(v).split()).lower() if v is not None else None  # noqa: E731
    return norm(a) == norm(b)


def item_ok(got: dict, exp: dict) -> bool:
    return all(same(got.get(k), exp[k]) for k in ("description", "quantity", "unit_price", "amount"))


def main() -> None:
    expected = json.loads((ROOT / "samples" / "expected.json").read_text())
    rows, field_hits, field_total, item_hits, item_total, seconds = [], 0, 0, 0, 0, []

    for name, exp in expected.items():
        _, inv, secs = extract_pdf(ROOT / "samples" / name)
        got = inv.model_dump()
        seconds.append(secs)
        wrong = [f for f in FIELDS if not same(got[f], exp[f])]
        field_hits += len(FIELDS) - len(wrong)
        field_total += len(FIELDS)

        hits = sum(1 for g, e in zip(got["line_items"], exp["line_items"]) if item_ok(g, e))
        item_hits += hits
        item_total += len(exp["line_items"])
        flagged = [i.field for i in validate(inv)]
        rows.append((name, len(FIELDS) - len(wrong), hits, len(exp["line_items"]),
                     len(got["line_items"]), wrong, flagged, secs))
        print(f"{name}: fields {len(FIELDS) - len(wrong)}/{len(FIELDS)}, items {hits}/{len(exp['line_items'])}, "
              f"flags {flagged}, {secs:.1f}s" + (f"  wrong: {wrong}" if wrong else ""))

    lines = [
        "# Extraction accuracy",
        "",
        f"Generated by `scripts/evaluate.py` on {date.today()}, model `{config.MODEL}` via Ollama, "
        f"{platform.system()} {platform.machine()}.",
        "",
        f"- **Header fields:** {field_hits}/{field_total} correct ({field_hits / field_total:.0%})",
        f"- **Line items (all 4 fields right):** {item_hits}/{item_total} correct ({item_hits / item_total:.0%})",
        f"- **Average time per document:** {sum(seconds) / len(seconds):.1f} s",
        "",
        "| Document | Header fields | Line items | Wrong fields | Flagged by validation | Time |",
        "|---|---:|---:|---|---|---:|",
    ]
    for name, f_ok, i_ok, i_exp, i_got, wrong, flagged, secs in rows:
        lines.append(f"| {name} | {f_ok}/{len(FIELDS)} | {i_ok}/{i_exp}"
                     + (f" (got {i_got})" if i_got != i_exp else "")
                     + f" | {', '.join(wrong) or '–'} | {', '.join(flagged) or '–'} | {secs:.1f} s |")
    lines += ["", "`06_wrong_total.pdf` has a wrong printed total on purpose, so it should be flagged on `total`.", ""]
    (ROOT / "docs" / "evaluation.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
